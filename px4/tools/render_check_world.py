"""Phase 8 step 1: write the render-check world. A static block city of 1500 boxes (seeded) on a
2 km ground under a shadow-casting sun, three 1280x720 30 Hz cameras (chase, pad close-up,
high-wide) and the 320x240 10 Hz downward marker camera, all on static models.

Usage: render_check_world.py <out.sdf>"""

import random
import sys
from pathlib import Path

SEED = 8
N_BOXES = 1500
HALF_SIDE_M = 600.0


def camera(name: str, pose: str, width: int, height: int, hz: int, fov_rad: float) -> str:
    return f"""    <model name="{name}">
      <static>true</static>
      <pose>{pose}</pose>
      <link name="link">
        <sensor name="{name}" type="camera">
          <topic>render_check/{name}</topic>
          <update_rate>{hz}</update_rate>
          <always_on>1</always_on>
          <camera>
            <horizontal_fov>{fov_rad}</horizontal_fov>
            <image><width>{width}</width><height>{height}</height><format>R8G8B8</format></image>
            <clip><near>0.1</near><far>5000</far></clip>
          </camera>
        </sensor>
      </link>
    </model>
"""


def main() -> int:
    rng = random.Random(SEED)
    boxes = []
    for i in range(N_BOXES):
        x, y = rng.uniform(-HALF_SIDE_M, HALF_SIDE_M), rng.uniform(-HALF_SIDE_M, HALF_SIDE_M)
        w, d, h = rng.uniform(8, 30), rng.uniform(8, 30), rng.uniform(6, 40)
        g = rng.uniform(0.55, 0.8)
        boxes.append(f'        <visual name="b{i}"><pose>{x:.1f} {y:.1f} {h / 2:.1f} 0 0 {rng.uniform(0, 3.14):.2f}</pose>'
                     f'<geometry><box><size>{w:.1f} {d:.1f} {h:.1f}</size></box></geometry>'
                     f'<material><diffuse>{g:.2f} {g:.2f} {g - 0.05:.2f} 1</diffuse>'
                     f'<ambient>{g:.2f} {g:.2f} {g - 0.05:.2f} 1</ambient></material></visual>')
    cams = (camera("chase", "-20 -20 80 0 0.5 0.785", 1280, 720, 30, 1.2)
            + camera("pad_close", "30 0 10 0 0.35 3.1416", 1280, 720, 30, 1.0)
            + camera("high_wide", "-700 -700 400 0 0.35 0.785", 1280, 720, 30, 1.1)
            + camera("marker_down", "0 0 6 0 1.5708 0", 320, 240, 10, 1.2))
    newline = "\n"
    Path(sys.argv[1]).write_text(f"""<?xml version="1.0"?>
<!-- Generated by px4/tools/render_check_world.py; do not edit. -->
<sdf version="1.9">
  <world name="render_check">
    <physics type="ode"><max_step_size>0.004</max_step_size><real_time_factor>1</real_time_factor></physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <scene><ambient>0.45 0.45 0.45 1</ambient><background>0.62 0.72 0.85 1</background><shadows>true</shadows><grid>false</grid></scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 500 0 0 0</pose>
      <diffuse>0.9 0.9 0.85 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.5 0.3 -0.8</direction>
    </light>
    <model name="ground">
      <static>true</static>
      <link name="link">
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>2000 2000</size></plane></geometry>
          <material><diffuse>0.45 0.55 0.4 1</diffuse><ambient>0.45 0.55 0.4 1</ambient></material></visual>
      </link>
    </model>
    <model name="city">
      <static>true</static>
      <link name="link">
{newline.join(boxes)}
      </link>
    </model>
{cams}  </world>
</sdf>
""")
    return 0


if __name__ == "__main__":
    sys.exit(main())
