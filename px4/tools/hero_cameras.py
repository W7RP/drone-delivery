"""Phase 8 step 5: the clip's three render cameras for one run (docs/hero-clip.md 5).

Each camera is its own static model with no inertia and no collision, so nothing it does can
reach the flight dynamics: the chase camera is posed every sim step by the dd_chase_camera
system (px4/sim/systems) from the drone's pose; the pad close-up (fixed at pad B) and the
high-wide overview (fixed, looking down the lane from behind pad A) never move. The downward
marker camera on the drone is untouched.

Writes <run>/models/dd_cam_<name>/model.sdf, <run>/cameras.json (spawn poses and topics for
lib/sitl.sh and the frame recorder) and <run>/server_cameras.config (the given server config
plus the chase system). Placement is in pipeline/hero/hero.yaml (`cameras`).

Usage: hero_cameras.py --run DIR --server-config IN"""

import argparse
import json
import math
import sys
from pathlib import Path

import yaml

PX4 = Path(__file__).resolve().parents[1]
HERO_CFG = PX4.parent / "pipeline" / "hero" / "hero.yaml"
TOPIC = "/dd/cam/{}"


def look_at(eye: list[float], target: list[float]) -> tuple[float, float]:
    """(pitch, yaw) that point a Gazebo camera (looking along +X) from eye to target."""
    dx, dy, dz = (t - e for t, e in zip(target, eye))
    return math.atan2(-dz, math.hypot(dx, dy)), math.atan2(dy, dx)


def camera_model(name: str, cam: dict) -> str:
    return f"""<?xml version="1.0"?>
<!-- Generated by px4/tools/hero_cameras.py; do not edit. A render camera on a static,
     massless model: it cannot touch the flight. -->
<sdf version="1.9">
  <model name="dd_cam_{name}">
    <static>true</static>
    <link name="link">
      <sensor name="cam" type="camera">
        <topic>{TOPIC.format(name)}</topic>
        <update_rate>{cam['rate_hz']}</update_rate>
        <always_on>1</always_on>
        <camera>
          <horizontal_fov>{cam['hfov_rad']}</horizontal_fov>
          <image><width>{cam['width']}</width><height>{cam['height']}</height><format>R8G8B8</format></image>
          <clip><near>{cam['near_m']}</near><far>{cam['far_m']}</far></clip>
        </camera>
      </sensor>
    </link>
  </model>
</sdf>
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", type=Path, required=True)
    ap.add_argument("--server-config", type=Path, required=True)
    a = ap.parse_args()
    cfg = yaml.safe_load(HERO_CFG.read_text())["cameras"]
    scene = json.loads((a.run / "scene.json").read_text())
    vehicle = json.loads((a.run / "vehicle.json").read_text())
    lane = json.loads((a.run / "lane.json").read_text())
    ground = scene.get("pad_ground_z_m", {"A": 0.0, "B": 0.0})

    def pad_center(pad: str) -> list[float]:
        i, o = scene["spots"][f"{pad}_IN"]["enu_m"], scene["spots"][f"{pad}_OUT"]["enu_m"]
        return [(i[0] + o[0]) / 2, (i[1] + o[1]) / 2, ground[pad]]

    a_c, b_c = pad_center("A"), pad_center("B")
    along = [b_c[0] - a_c[0], b_c[1] - a_c[1]]
    norm = math.hypot(*along)
    ux, uy = along[0] / norm, along[1] / norm
    poses = {}
    p = cfg["pad"]
    eye = [b_c[0] + p["offset_m"][0], b_c[1] + p["offset_m"][1], b_c[2] + p["offset_m"][2]]
    poses["pad"] = (eye, look_at(eye, [b_c[0], b_c[1], b_c[2] + p["look_up_m"]]))
    w = cfg["wide"]
    # Behind pad A on the lane line, to its left, looking at a point down the lane.
    eye = [a_c[0] - ux * w["behind_m"] - uy * w["left_m"], a_c[1] - uy * w["behind_m"] + ux * w["left_m"],
           a_c[2] + w["up_m"]]
    target = [a_c[0] + ux * w["look_along_m"], a_c[1] + uy * w["look_along_m"], a_c[2]]
    poses["wide"] = (eye, look_at(eye, target))
    c = cfg["chase"]
    start = vehicle["spawn"][vehicle["model"]]
    eye = [start[0] - ux * c["back_m"], start[1] - uy * c["back_m"], start[2] + c["up_m"]]
    poses["chase"] = (eye, look_at(eye, start[:3]))

    spawn = {}
    for name in ("chase", "pad", "wide"):
        model = f"dd_cam_{name}"
        path = a.run / "models" / model / "model.sdf"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(camera_model(name, cfg))
        eye, (pitch, yaw) = poses[name]
        cp, sp, cy, sy = math.cos(pitch / 2), math.sin(pitch / 2), math.cos(yaw / 2), math.sin(yaw / 2)
        spawn[model] = {"xyz_m": [round(v, 3) for v in eye], "pitch_rad": round(pitch, 5), "yaw_rad": round(yaw, 5),
                        # Hamilton, w-x-y-z: yaw about z, then pitch about the new y.
                        "quat_wxyz": [round(cy * cp, 6), round(-sy * sp, 6), round(cy * sp, 6), round(sy * cp, 6)],
                        "topic": TOPIC.format(name), "name": name}
    (a.run / "cameras.json").write_text(json.dumps({"comment": "Generated by px4/tools/hero_cameras.py.",
                                                    "lane_id": lane["lane_id"], "cameras": spawn}, indent=1) + "\n")
    system = f"""    <plugin entity_name="*" entity_type="world" filename="dd_chase_camera" name="dd::ChaseCamera">
      <target>{vehicle['model']}</target>
      <camera>dd_cam_chase</camera>
      <back_m>{c['back_m']}</back_m>
      <up_m>{c['up_m']}</up_m>
      <side_m>{c['side_m']}</side_m>
      <lag_s>{c['lag_s']}</lag_s>
      <min_track_speed_mps>{c['min_track_speed_mps']}</min_track_speed_mps>
    </plugin>
  </plugins>"""
    text = a.server_config.read_text()
    if text.count("</plugins>") != 1:
        raise SystemExit(f"{a.server_config}: expected one </plugins>")
    (a.run / "server_cameras.config").write_text(text.replace("</plugins>", system))
    print(json.dumps(spawn))
    return 0


if __name__ == "__main__":
    sys.exit(main())
