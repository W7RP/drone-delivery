"""Phase 4 step 3: write the corridor world (sim/worlds/dd_corridor.sdf) and one ArUco marker
model per spot (sim/models/dd_marker_<id>/) from config/lane.json and config/flight.yaml.

The world is the flat corridor of one lane in local ENU with the hub at the origin: a ground
plane, pad A at the origin and pad B at the lane's far end, each with an IN and an OUT slab and
a marker beside each slab. No buildings, no terrain. The vehicle and pods are spawned per run
(tools/make_vehicle.py)."""

import json
import sys
from pathlib import Path

import cv2
import yaml

PX4 = Path(__file__).resolve().parents[1]
LANE = PX4 / "config" / "lane.json"
FLIGHT = PX4 / "config" / "flight.yaml"
WORLD = PX4 / "sim" / "worlds" / "dd_corridor.sdf"
SCENE = PX4 / "config" / "scene.json"
MODELS = PX4 / "sim" / "models"
WORLD_NAME = "dd_corridor"
MARKER_CELLS = 6  # a 4x4 ArUco code plus its black border
PX_PER_CELL = 32
SLAB_THICKNESS_M = 0.02
MARKER_THICKNESS_M = 0.005


def spots(lane: dict, cfg: dict) -> dict[str, tuple[float, float]]:
    """Spot centres in world ENU: IN west and OUT east of each pad position."""
    half = cfg["pads"]["spot_separation_m"] / 2
    out = {}
    for pad, key in (("A", "from_pad"), ("B", "to_pad")):
        x, y = lane[key]["enu_m"]
        out[f"{pad}_IN"] = (x - half, y)
        out[f"{pad}_OUT"] = (x + half, y)
    return out


def marker_png(marker_id: int, path: Path) -> None:
    """The marker with a one-cell white quiet zone, as a texture image."""
    dictionary = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_4X4_50)
    code = cv2.aruco.generateImageMarker(dictionary, marker_id, MARKER_CELLS * PX_PER_CELL)
    img = cv2.copyMakeBorder(code, PX_PER_CELL, PX_PER_CELL, PX_PER_CELL, PX_PER_CELL,
                             cv2.BORDER_CONSTANT, value=255)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not cv2.imwrite(str(path), img):
        raise RuntimeError(f"could not write {path}")


def marker_model(marker_id: int, side_m: float) -> None:
    name = f"dd_marker_{marker_id}"
    root = MODELS / name
    texture = f"materials/textures/aruco_{marker_id}.png"
    marker_png(marker_id, root / texture)
    full = side_m * (MARKER_CELLS + 2) / MARKER_CELLS
    (root / "model.config").write_text(f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>ArUco DICT_4X4_50 id {marker_id}, {side_m} m black square plus a white quiet zone.
Generated by px4/tools/make_world.py.</description>
</model>
""")
    (root / "model.sdf").write_text(f"""<?xml version="1.0"?>
<!-- Generated by px4/tools/make_world.py; do not edit. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="link">
      <visual name="marker">
        <geometry><box><size>{full:.4f} {full:.4f} {MARKER_THICKNESS_M}</size></box></geometry>
        <material>
          <diffuse>1 1 1 1</diffuse>
          <ambient>1 1 1 1</ambient>
          <pbr><metal><albedo_map>{texture}</albedo_map><roughness>1</roughness><metalness>0</metalness></metal></pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
""")


def slab(name: str, x: float, y: float, side: float) -> str:
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {SLAB_THICKNESS_M / 2} 0 0 0</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{side} {side} {SLAB_THICKNESS_M}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{side} {side} {SLAB_THICKNESS_M}</size></box></geometry>
          <material><diffuse>0.45 0.45 0.47 1</diffuse><ambient>0.45 0.45 0.47 1</ambient></material></visual>
      </link>
    </model>"""


def world_sdf(lane: dict, cfg: dict) -> str:
    p = cfg["pads"]
    dx, dy = p["marker_offset_m"]
    parts = []
    for spot, (x, y) in spots(lane, cfg).items():
        parts.append(slab(f"slab_{spot}", x, y, p["slab_side_m"]))
        mid = p["marker_ids"][spot]
        parts.append(f"""
    <include>
      <uri>model://dd_marker_{mid}</uri>
      <name>marker_{spot}</name>
      <pose>{x + dx:.3f} {y + dy:.3f} {SLAB_THICKNESS_M + MARKER_THICKNESS_M / 2:.4f} 0 0 0</pose>
    </include>""")
    w = cfg["world"]
    a = lane["from_pad"]
    return f"""<?xml version="1.0"?>
<!-- Generated by px4/tools/make_world.py from config/lane.json and config/flight.yaml; do not
     edit. Lane {lane['lane_id']}: {a['name']} (origin) to {lane['to_pad']['name']},
     {lane['length_m']:.1f} m. Local ENU, hub at the origin, flat ground. -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene>
      <grid>false</grid>
      <ambient>0.5 0.5 0.5 1</ambient>
      <background>0.7 0.7 0.7 1</background>
      <shadows>false</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>0 0 100 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>{w['ground_side_m']} {w['ground_side_m']}</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>{w['ground_side_m']} {w['ground_side_m']}</size></plane></geometry>
          <material><diffuse>0.55 0.6 0.5 1</diffuse><ambient>0.55 0.6 0.5 1</ambient></material></visual>
      </link>
    </model>{''.join(parts)}
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{a['lat_deg']}</latitude_deg>
      <longitude_deg>{a['lon_deg']}</longitude_deg>
      <elevation>{w['elevation_m']}</elevation>
    </spherical_coordinates>
  </world>
</sdf>
"""


def main() -> int:
    lane = json.loads(LANE.read_text())
    cfg = yaml.safe_load(FLIGHT.read_text())
    for mid in cfg["pads"]["marker_ids"].values():
        marker_model(mid, cfg["pads"]["marker_side_m"])
    WORLD.parent.mkdir(parents=True, exist_ok=True)
    WORLD.write_text(world_sdf(lane, cfg))
    p = cfg["pads"]
    scene = {
        "comment": "Generated by px4/tools/make_world.py; do not edit. World ENU metres.",
        "world": WORLD_NAME,
        "slab_top_m": SLAB_THICKNESS_M,
        "marker_side_m": p["marker_side_m"],
        "marker_offset_m": p["marker_offset_m"],
        "spots": {name: {"enu_m": [x, y], "marker_id": p["marker_ids"][name],
                         "marker_enu_m": [x + p["marker_offset_m"][0], y + p["marker_offset_m"][1]]}
                  for name, (x, y) in spots(lane, cfg).items()},
    }
    SCENE.write_text(json.dumps(scene, indent=1) + "\n")
    for spot, (x, y) in spots(lane, cfg).items():
        print(f"{spot}: spot ({x:.2f}, {y:.2f}), marker id {cfg['pads']['marker_ids'][spot]}")
    print(f"wrote {WORLD.relative_to(PX4.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
