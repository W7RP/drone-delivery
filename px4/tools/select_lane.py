"""Phase 4 step 2: pick the lane to fly and record everything the SITL flight takes from the
rest of the repo, in px4/config/lane.json.

The default lane runs from the Strip District hub to the nearest Oakland pad of the Pittsburgh
catalog. `--lane-id N --out <file>` records any directed lane of the catalog instead (held-out
flights), into a run directory rather than px4/config.
Positions are local ENU metres with the hub as origin, using the sim's projection (spec section
0). Commanded cruise speed comes from the scenario's flight model; the sim has no altitude
(spec A03), so the cruise altitude is the pipeline's airspace placeholder (params.yaml), the
altitude the lanes were checked against."""

import argparse
import hashlib
import json
import math
import struct
import sys
import tomllib
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[2]
# Phase 3's catalog and flight values: the placeholder variant keeps them byte-identical, while
# the fitted variant's network drops pads and renumbers its lanes (spec A65).
SCENARIO = REPO / "configs" / "parts_logistics_pittsburgh_placeholder"
DERIVED = SCENARIO / "derived"
PIPELINE_PARAMS = REPO / "pipeline" / "params.yaml"
OUT = REPO / "px4" / "config" / "lane.json"
EARTH_RADIUS_M = 6_371_000.0
M_PER_FT = 0.3048
HUB_CLUSTER, DEST_CLUSTER = "strip_district", "oakland"
DRONE_KEYS = ("empty_mass_kg", "latch_mass_kg", "mtow_kg", "cruise_speed_mps", "takeoff_s",
              "approach_s", "go_around_s", "hop_s")


def enu_from_geo(lat, lon, lat0, lon0):
    """Spec section 0: equirectangular about (lat0, lon0)."""
    x = EARTH_RADIUS_M * math.cos(math.radians(lat0)) * math.radians(lon - lon0)
    y = EARTH_RADIUS_M * math.radians(lat - lat0)
    return x, y


def read_lanes(path: Path):
    """(from_pad, to_pad, length_m) per directed lane of lanes.csr.bin (spec 9.1); lane_id is
    the list index. Only the arrays needed here; the sim and the pipeline validate the file."""
    data = path.read_bytes()
    magic, major, _, header_bytes, n_pads, n_lanes, _ = struct.unpack_from("<8sHHIIIQ", data)
    if magic != b"DDLANES\0" or major != 1:
        raise ValueError(f"{path}: not a version 1 lanes file")
    at = header_bytes
    row = struct.unpack_from(f"<{n_pads + 1}I", data, at)
    at += 4 * (n_pads + 1)
    at += -at % 8
    to = struct.unpack_from(f"<{n_lanes}H", data, at)
    at += 2 * n_lanes
    at += -at % 8
    length = struct.unpack_from(f"<{n_lanes}f", data, at)
    frm = [p for p in range(n_pads) for _ in range(row[p], row[p + 1])]
    return list(zip(frm, to, length))


def q(table):
    return table["value"]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lane-id", type=int, default=None)
    ap.add_argument("--out", type=Path, default=OUT)
    args = ap.parse_args()
    report = json.loads((DERIVED / "report.json").read_text())
    catalog_bytes = (DERIVED / "pads.toml").read_bytes()
    pads = tomllib.loads(catalog_bytes.decode())["pads"]
    scenario = tomllib.loads((SCENARIO / "scenario.toml").read_text())
    params = yaml.safe_load(PIPELINE_PARAMS.read_text())
    lanes = read_lanes(DERIVED / "lanes.csr.bin")

    hub = next(p for p in report["pads"] if p["is_hub"] and p["cluster"] == HUB_CLUSTER)
    candidates = [(i, f, t, l) for i, (f, t, l) in enumerate(lanes)
                  if f == hub["id"] and report["pads"][t]["cluster"] == DEST_CLUSTER]
    lane_id, a, b, length = min(candidates, key=lambda c: (c[3], c[0]))
    if args.lane_id is not None:
        a, b, length = lanes[args.lane_id]
        lane_id = args.lane_id
    reverse_id = next(i for i, (f, t, _) in enumerate(lanes) if (f, t) == (b, a))
    pa, pb = pads[a], pads[b]
    lat0, lon0 = q(pa["lat_deg"]), q(pa["lon_deg"])
    bx, by = enu_from_geo(q(pb["lat_deg"]), q(pb["lon_deg"]), lat0, lon0)
    d = scenario["drone"]
    lane = {
        "comment": "Generated by px4/tools/select_lane.py; do not edit.",
        "lane_id": lane_id,
        "reverse_lane_id": reverse_id,
        "length_m": length,
        "enu_length_m": math.hypot(bx, by),
        "from_pad": {"id": a, "name": pa["name"], "osm_name": report["pads"][a]["osm_name"],
                     "lat_deg": lat0, "lon_deg": lon0, "enu_m": [0.0, 0.0]},
        "to_pad": {"id": b, "name": pb["name"], "osm_name": report["pads"][b]["osm_name"],
                   "lat_deg": q(pb["lat_deg"]), "lon_deg": q(pb["lon_deg"]), "enu_m": [bx, by]},
        "drone": {k: q(d[k]) for k in DRONE_KEYS},
        "payload": {k: q(v) for k, v in scenario["payload"].items()},
        "pad_ops": {k: q(scenario["pad_ops"][k]) for k in
                    ("release_s", "release_verify_s", "latch_s", "latch_verify_s",
                     "p_marker_detect", "max_go_arounds")},
        "cruise_alt_m": q(params["airspace"]["cruise_altitude_agl_ft"]) * M_PER_FT,
        "sources": {
            "pads.toml_sha256": hashlib.sha256(catalog_bytes).hexdigest(),
            "scenario": str(SCENARIO.relative_to(REPO) / "scenario.toml"),
            "cruise_altitude": "pipeline/params.yaml airspace.cruise_altitude_agl_ft",
        },
    }
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(lane, indent=1) + "\n")
    print(f"lane {lane_id}: {pa['name']} -> {pb['name']}, {length:.1f} m "
          f"(ENU {bx:.1f}, {by:.1f}), cruise {lane['drone']['cruise_speed_mps']} m/s at "
          f"{lane['cruise_alt_m']:.2f} m")
    return 0


if __name__ == "__main__":
    sys.exit(main())
