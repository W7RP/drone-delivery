"""Phase 8 step 6: the clip's drone-vs-truck panel for its lane (docs/hero-clip.md 6).

From the demo scenario at seed 42 (deliveries.csv): the SHIPMENT orders on the clip's lane
(origin and destination are its pads) delivered by drone to their destination. The panel shows
the median drone door-to-door time, the split of the median order (pod wait, queue, pad service,
flight; they sum to its door-to-door, spec M2), and the median truck door-to-door of the same
orders. With an even count the lower median order is used for both. Writes hero/out/panel.json."""

import json
import statistics
import tempfile
from pathlib import Path

from .common import OUT, config, demo_network, run_demo

SPLIT = ("pod_wait_s", "queue_s", "pad_service_s", "flight_s")


def lane_panel(rows: list[dict], a: int, b: int) -> dict:
    orders = [r for r in rows if r["kind"] == "SHIPMENT" and r["status"] == "DELIVERED"
              and int(r["origin_pad"]) == a and int(r["dest_pad"]) == b and r["delivered_pad"] == r["dest_pad"]]
    if not orders:
        raise RuntimeError(f"no drone-delivered orders from pad {a} to pad {b}")
    orders.sort(key=lambda r: (float(r["drone_door_to_door_s"]), int(r["order_id"])))
    median = orders[(len(orders) - 1) // 2]
    return {"orders": len(orders),
            "drone_median_s": float(median["drone_door_to_door_s"]),
            "median_order_id": int(median["order_id"]),
            "median_order_split_s": {k: float(median[k]) for k in SPLIT},
            "median_order_truck_s": float(median["truck_door_to_door_s"]),
            "truck_median_s": statistics.median_low(float(r["truck_door_to_door_s"]) for r in orders)}


def main() -> dict:
    cfg = config()["lane_choice"]
    chosen = json.loads((OUT / "lane.json").read_text())["chosen"]
    with tempfile.TemporaryDirectory() as tmp:
        rows = run_demo(cfg["demo_seed"], Path(tmp) / "out")
    _, pads, lanes, _ = demo_network()
    lane = chosen["lane_id"]
    a, b = int(lanes.from_pad[lane]), int(lanes.to_pad[lane])
    doc = {"comment": "Generated by pipeline/run.sh hero panel; do not edit. Demo scenario "
                      "parts_logistics_pittsburgh_vtol_demo, deliveries.csv.",
           "lane_id": lane, "seed": cfg["demo_seed"], "from": pads[a]["name"], "to": pads[b]["name"],
           **lane_panel(rows, a, b)}
    (OUT / "panel.json").write_text(json.dumps(doc, indent=1) + "\n")
    print(json.dumps(doc, indent=1))
    return doc


if __name__ == "__main__":
    main()
