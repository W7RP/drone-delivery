"""Phase 8 step 2: pick the clip's lane by rule (docs/hero-clip.md 2).

Candidates are lanes of the VTOL demo network with at least one drone-delivered order in the
demo scenario at seed 42 (status DELIVERED, delivered on its destination pad), no longer than
the network's 5 kg range (report.json lane_range_m), whose straight line crosses an OSM water
polygon. Choose the highest road / straight-line ratio (truck road metres over the great-circle
distance between the pads, as ddpipe.truck.detour_ratios), then the shortest, then the lowest
lane id. With no water crossing, the water condition is dropped and that is recorded.
Writes hero/out/lane.json."""

import json
import tempfile
from collections import Counter
from pathlib import Path

import shapely

from ddpipe import fetch, osm, pads as ddpads
from ddpipe.geo import great_circle_m
from ddpipe.params import load

from .common import CACHE, OSM_FILE, OUT, RAW, config, demo_network, lane_index, run_demo


def water_union():
    manifest = json.loads((RAW / "manifest.json").read_text())
    sources = fetch.load_sources()
    extract = osm.read_cached(RAW / OSM_FILE, manifest["files"]["osm_pennsylvania"]["sha256"],
                              CACHE, sources["area"], ddpads.site_keys(load("sites.yaml")))
    return shapely.union_all([shapely.make_valid(g) for g in extract.water])


def main() -> dict:
    cfg = config()["lane_choice"]
    derived, pads, lanes, truck = demo_network()
    report = json.loads((derived / "report.json").read_text())
    range_m = report["lane_range_m"]
    with tempfile.TemporaryDirectory() as tmp:
        rows = run_demo(cfg["demo_seed"], Path(tmp) / "out")
    delivered = Counter((int(r["origin_pad"]), int(r["dest_pad"])) for r in rows
                        if r["kind"] == "SHIPMENT" and r["status"] == "DELIVERED"
                        and r["delivered_pad"] == r["dest_pad"])
    water = water_union()
    table = []
    for (a, b), n in sorted(delivered.items()):
        lane = lane_index(lanes, a, b)
        if lane is None:
            continue
        pa, pb = pads[a], pads[b]
        lat_a, lon_a = pa["lat_deg"]["value"], pa["lon_deg"]["value"]
        lat_b, lon_b = pb["lat_deg"]["value"], pb["lon_deg"]["value"]
        straight = float(great_circle_m(lat_a, lon_a, lat_b, lon_b))
        line = shapely.LineString([(lon_a, lat_a), (lon_b, lat_b)])
        table.append({"lane_id": lane, "from": pa["name"], "to": pb["name"],
                      "drone_delivered": n, "length_m": round(float(lanes.length_m[lane]), 1),
                      "within_range": bool(lanes.length_m[lane] <= range_m),
                      "crosses_water": bool(line.intersects(water)),
                      "road_m": round(float(truck.road_m[a, b]), 1),
                      "road_over_straight": round(float(truck.road_m[a, b]) / straight, 4)})
    in_range = [t for t in table if t["within_range"]]
    wet = [t for t in in_range if t["crosses_water"]]
    pool, water_rule = (wet, "applied") if wet else (in_range, "dropped: no candidate crosses water")
    if not pool:
        raise RuntimeError("no lane has drone-delivered orders within range")
    best = min(pool, key=lambda t: (-t["road_over_straight"], t["length_m"], t["lane_id"]))
    doc = {"comment": "Generated by pipeline/run.sh hero lane; do not edit.",
           "demo": str(derived.parent.name), "seed": cfg["demo_seed"], "range_m_5kg": range_m,
           "water_rule": water_rule,
           "rule": "highest road/straight, then shortest, then lowest lane id",
           "chosen": best, "candidates": table}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "lane.json").write_text(json.dumps(doc, indent=1) + "\n")
    for t in table:
        print(f"lane {t['lane_id']:2d} {t['from']:>24s} -> {t['to']:<34s} n={t['drone_delivered']:3d} "
              f"{t['length_m']:8.1f} m water={t['crosses_water']!s:5s} road/straight {t['road_over_straight']:.3f}")
    print(f"chosen: lane {best['lane_id']} ({water_rule})")
    return doc


if __name__ == "__main__":
    main()
