def terrain_grid(cfg, region, enu: Enu, dem: Dem, pads_enu, pad_elev, water_parts) -> tuple[Grid, list]:
    g = cfg["terrain_grid_m"]
    minx, miny, maxx, maxy = region.bounds
    x0, y0 = math.floor(minx / g) * g, math.floor(miny / g) * g
    nx, ny = int(math.ceil((maxx - x0) / g)) + 1, int(math.ceil((maxy - y0) / g)) + 1
    xs, ys = x0 + g * np.arange(nx), y0 + g * np.arange(ny)
    X, Y = np.meshgrid(xs, ys)
    lon, lat = enu.lonlat(X, Y)
    z = dem.bilinear(lon, lat)
    # Water: hydro-flattened in 3DEP, so the median DEM inside a polygon is its surface. Terrain
    # under it is pushed below the surface so no bank pokes through the slab.
    water = []
    for part in water_parts:
        inside = shapely.contains_xy(part, X, Y)
        if inside.any():
            surface = float(np.median(z[inside]))
        else:
            rp = part.representative_point()
            surface = float(dem.bilinear(*enu.lonlat(rp.x, rp.y)))
        z[inside] = np.minimum(z[inside], surface - cfg["water_depth_m"])
        water.append((part, surface))
    # Pads: flat at the pad's ground, blending back to the DEM.
    for (px, py), elev in zip(pads_enu, pad_elev):
        r = np.hypot(X - px, Y - py)
        w = np.clip((r - cfg["pad_flat_radius_m"]) / cfg["pad_blend_m"], 0.0, 1.0)
        z = (1 - w) * (elev - cfg["apron_inset_m"]) + w * z
    cx, cy = np.meshgrid(xs[:-1] + g / 2, ys[:-1] + g / 2)
    keep = shapely.contains_xy(region, cx, cy)
    return Grid(x0, y0, g, z, keep), water


def terrain_meshes(grid: Grid, bands: list[dict], elev_a: float) -> list[Mesh]:
    ny, nx = grid.z.shape
    zr = grid.z - elev_a
    dzdy, dzdx = np.gradient(zr, grid.g)
    normals = np.stack([-dzdx, -dzdy, np.ones_like(zr)], axis=-1)
    xs, ys = grid.x0 + grid.g * np.arange(nx), grid.y0 + grid.g * np.arange(ny)
    X, Y = np.meshgrid(xs, ys)
    idx = np.arange(nx * ny).reshape(ny, nx)
    jj, ii = np.nonzero(grid.keep)
    a, b, c, d = idx[jj, ii], idx[jj, ii + 1], idx[jj + 1, ii + 1], idx[jj + 1, ii]
    tris = np.concatenate([np.stack([a, b, c], 1), np.stack([a, c, d], 1)])
    flat_z = grid.z.ravel()
    mean_elev = flat_z[tris].mean(axis=1)
    band_of = np.digitize(mean_elev, [b["below_m"] for b in bands[:-1]])
    verts = np.stack([X.ravel(), Y.ravel(), zr.ravel()], 1)
    meshes = []
    for k in range(len(bands)):
        t = tris[band_of == k]
        order = np.lexsort((t[:, 2], t[:, 1], t[:, 0]))
        t = t[order]
        used = np.unique(t)
        remap = np.full(len(verts), -1, dtype=np.int64)
        remap[used] = np.arange(len(used))
        m = Mesh()
        if len(t):
            m.add(verts[used], normals.reshape(-1, 3)[used], remap[t])
        meshes.append(m)
    return meshes


def water_mesh(water, offset_m: float, elev_a: float) -> Mesh:
    m = Mesh()
    for part, surface in water:
        t = flat_triangles(part)
        if not len(t):
            continue
        xy = t.reshape(-1, 2)
        v = np.column_stack([xy, np.full(len(xy), surface - elev_a + offset_m)])
        m.add(v, np.tile([0.0, 0.0, 1.0], (len(v), 1)), np.arange(len(v)).reshape(-1, 3))
    return m


def road_mesh(roads, region, enu: Enu, grid: Grid, cfg: dict, elev_a: float) -> tuple[Mesh, int]:
    widths = cfg["road_width_m"]
    lon_min, lat_min = enu.lonlat(region.bounds[0], region.bounds[1])
    lon_max, lat_max = enu.lonlat(region.bounds[2], region.bounds[3])
    m, ways = Mesh(), 0
    for road in roads:
        if (road.lon_deg.max() < lon_min or road.lon_deg.min() > lon_max
                or road.lat_deg.max() < lat_min or road.lat_deg.min() > lat_max):
            continue
        if road.tags.get("tunnel") not in (None, "no"):
            continue
        hw = road.tags["highway"].removesuffix("_link")
        width = widths.get(hw, widths["other"])
        x, y = enu.xy(road.lon_deg, road.lat_deg)
        line = shapely.LineString(np.column_stack([x, y]))
        clipped = line.intersection(region)
        bridge = road.tags.get("bridge") not in (None, "no")
        if bridge:
            # A bridge deck spans between its ends; the ground under it is the river.
            ends = grid.surface([x[0], x[-1]], [y[0], y[-1]])
        used = False
        for part in shapely.get_parts(clipped):
            if not isinstance(part, shapely.LineString) or part.length <= 0:
                continue
            c = np.asarray(shapely.segmentize(part, cfg["road_step_m"]).coords)[:, :2]
            seg = np.diff(c, axis=0)
            length = np.hypot(seg[:, 0], seg[:, 1])
            ok = length > 1e-6
            if not ok.any():
                continue
            p, q, seg, length = c[:-1][ok], c[1:][ok], seg[ok], length[ok]
            nrm = np.column_stack([-seg[:, 1], seg[:, 0]]) / length[:, None] * width / 2
            corners = np.stack([p - nrm, p + nrm, q + nrm, q - nrm], axis=1).reshape(-1, 2)
            zs = grid.surface(corners[:, 0], corners[:, 1])
            if bridge:
                s = shapely.line_locate_point(line, shapely.points(corners), normalized=True)
                zs = np.maximum(zs, ends[0] + (ends[1] - ends[0]) * s)
            v = np.column_stack([corners, zs - elev_a + cfg["road_offset_m"]])
            k = np.arange(len(p))[:, None] * 4
            # Corners run right-left-left-right of the travel direction: these two triangles are
            # counter-clockwise from above.
            faces = np.concatenate([k + [0, 2, 1], k + [0, 3, 2]]).reshape(-1, 3)
            m.add(v, np.tile([0.0, 0.0, 1.0], (len(v), 1)), faces)
            used = True
        ways += used
    return m, ways


def building_mesh(selected, grid: Grid, tolerance_m: float, cfg: dict, elev_a: float) -> tuple[Mesh, list]:
    m, prisms = Mesh(), []
    for b in selected:
        geom = b["geom"].simplify(tolerance_m, preserve_topology=True) if tolerance_m > 0 else b["geom"]
        for poly in polygons(geom):
            ext = np.asarray(poly.exterior.coords)
            ground = grid.surface(ext[:, 0], ext[:, 1])
            base = float(ground.min()) - cfg["building_sink_m"]
            top = float(ground.min()) + b["height_m"]
            if top <= float(ground.max()):
                top = float(ground.max()) + cfg["min_exposed_m"]
            # Walls: each ring edge; exterior counter-clockwise, holes clockwise, so (dy, -dx)
            # points out of the solid either way.
            for ring in [poly.exterior, *poly.interiors]:
                c = np.asarray(ring.coords)[:, :2]
                p, q = c[:-1], c[1:]
                d = q - p
                keep = np.hypot(d[:, 0], d[:, 1]) > 1e-6
                p, q, d = p[keep], q[keep], d[keep]
                out = np.column_stack([d[:, 1], -d[:, 0], np.zeros(len(d))])
                zb, zt = base - elev_a, top - elev_a
                v = np.stack([np.column_stack([p, np.full(len(p), zb)]), np.column_stack([q, np.full(len(p), zb)]),
                              np.column_stack([q, np.full(len(p), zt)]), np.column_stack([p, np.full(len(p), zt)])],
                             axis=1).reshape(-1, 3)
                k = np.arange(len(p))[:, None] * 4
                m.add(v, np.repeat(out, 4, axis=0), np.concatenate([k + [0, 1, 2], k + [0, 2, 3]]).reshape(-1, 3))
            roof = flat_triangles(poly)
            if len(roof):
                xy = roof.reshape(-1, 2)
                v = np.column_stack([xy, np.full(len(xy), top - elev_a)])
                m.add(v, np.tile([0.0, 0.0, 1.0], (len(v), 1)), np.arange(len(v)).reshape(-1, 3))
            prisms.append({"osm_id": b["osm_id"], "base_z_m": round(base - elev_a, NDIGITS),
                           "top_z_m": round(top - elev_a, NDIGITS),
                           "exterior_m": [[round(x, NDIGITS), round(y, NDIGITS)] for x, y in ext[:, :2]]})
    return m, prisms


def color(rgb: list[float]) -> str:
    return " ".join(f"{c:.3f}" for c in rgb) + " 1"


def visual(name: str, mesh_file: str, rgb: list[float], shadows: bool = True) -> str:
    return f"""      <visual name="{name}">
        <cast_shadows>{'true' if shadows else 'false'}</cast_shadows>
        <geometry><mesh><uri>model://{MODEL}/meshes/{mesh_file}</uri></mesh></geometry>
        <material><diffuse>{color(rgb)}</diffuse><ambient>{color(rgb)}</ambient><specular>0.05 0.05 0.05 1</specular></material>
      </visual>"""


def box_model(name: str, x: float, y: float, z_top: float, size: tuple[float, float, float], rgb) -> str:
    sx, sy, sz = size
    return f"""
    <model name="{name}">
      <static>true</static>
      <pose>{x:.3f} {y:.3f} {z_top - sz / 2:.3f} 0 0 0</pose>
      <link name="link">
        <collision name="c"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><diffuse>{color(rgb)}</diffuse><ambient>{color(rgb)}</ambient></material></visual>
      </link>
    </model>"""


def world_sdf(lane: dict, scene: dict, cfg: dict, meshes: list[tuple[str, str, list, bool]],
              pad_ground: dict, elev_a: float) -> str:
    parts = []
    for pad in ("A", "B"):
        ins, outs = scene["spots"][f"{pad}_IN"]["enu_m"], scene["spots"][f"{pad}_OUT"]["enu_m"]
        cx, cy = (ins[0] + outs[0]) / 2, (ins[1] + outs[1]) / 2
        parts.append(box_model(f"apron_{pad}", cx, cy, pad_ground[pad], (cfg["apron_side_m"], cfg["apron_side_m"],
                                                                     cfg["apron_thickness_m"]), cfg["apron_rgb"]))
    for spot, s in scene["spots"].items():
        zg = pad_ground[spot[0]]
        x, y = s["enu_m"]
        side = scene["slab_side_m"]
        parts.append(box_model(f"slab_{spot}", x, y, zg + SLAB_THICKNESS_M, (side, side, SLAB_THICKNESS_M),
                               [0.45, 0.45, 0.47]))
        mx, my = s["marker_enu_m"]
        parts.append(f"""
    <include>
      <uri>model://dd_marker_{s['marker_id']}</uri>
      <name>marker_{spot}</name>
      <pose>{mx:.3f} {my:.3f} {zg + SLAB_THICKNESS_M + MARKER_THICKNESS_M / 2:.4f} 0 0 0</pose>
    </include>""")
    vis = "\n".join(visual(*m) for m in meshes)
    sun = cfg["sun"]
    a, b = lane["from_pad"], lane["to_pad"]
    return f"""<?xml version="1.0"?>
<!-- Generated by pipeline/run.sh hero world; do not edit. Lane {lane['lane_id']}: {a['name']} (origin)
     to {b['name']}, {lane['length_m']:.1f} m, over USGS 3DEP terrain with OSM water, roads and
     buildings. Local ENU at pad A, z = 0 on pad A's ground ({elev_a:.2f} m NAVD88). -->
<sdf version="1.9">
  <world name="{WORLD_NAME}">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <scene>
      <grid>false</grid>
      <ambient>{color(cfg['ambient_rgb'])}</ambient>
      <background>{color(cfg['sky_rgb'])}</background>
      <shadows>true</shadows>
    </scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows>
      <pose>0 0 1000 0 0 0</pose>
      <diffuse>{color(sun['diffuse_rgb'])}</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>{' '.join(f'{c:.3f}' for c in sun['direction'])}</direction>
    </light>
    <model name="{MODEL}">
      <static>true</static>
      <link name="link">
{vis}
      </link>
    </model>{''.join(parts)}
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>{a['lat_deg']}</latitude_deg>
      <longitude_deg>{a['lon_deg']}</longitude_deg>
      <elevation>{elev_a:.2f}</elevation>
    </spherical_coordinates>
  </world>
</sdf>
"""


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> dict:
    full = config()
    cfg = full["world"]
    lane_id = json.loads((OUT / "lane.json").read_text())["chosen"]["lane_id"]
    if HERO_DIR.exists():
        shutil.rmtree(HERO_DIR)
    (HERO_DIR / "models" / MODEL / "meshes").mkdir(parents=True)
    (HERO_DIR / "obstacles").mkdir()
    run_px4_tool("tools/select_lane.py", "--lane-id", str(lane_id), "--out", str(HERO_DIR / "lane.json"))
    with tempfile.TemporaryDirectory() as tmp:
        run_px4_tool("tools/make_world.py", "--lane", str(HERO_DIR / "lane.json"),
                     "--out-world", str(Path(tmp) / "flat.sdf"), "--out-scene", str(HERO_DIR / "scene.json"))
    lane = json.loads((HERO_DIR / "lane.json").read_text())
    scene = json.loads((HERO_DIR / "scene.json").read_text())

    manifest = json.loads((RAW / "manifest.json").read_text())
    sources = fetch.load_sources()
    dem = Dem(sources["area"])
    a, b = lane["from_pad"], lane["to_pad"]
    enu = Enu(a["lat_deg"], a["lon_deg"])
    bx, by = b["enu_m"]
    pads_enu = [(0.0, 0.0), (bx, by)]
    elev_a = float(dem.bilinear(a["lon_deg"], a["lat_deg"]))
    elev_b = float(dem.bilinear(b["lon_deg"], b["lat_deg"]))
    axis = shapely.LineString(pads_enu)
    region = shapely.union_all([axis.buffer(cfg["lane_buffer_m"]),
                                *(shapely.Point(p).buffer(cfg["pad_buffer_m"]) for p in pads_enu)])

    extract = osm.read_cached(RAW / OSM_FILE, manifest["files"]["osm_pennsylvania"]["sha256"], CACHE,
                              sources["area"], ddpads.site_keys(load("sites.yaml")))
    region_ll = shapely.box(*enu.lonlat(region.bounds[0], region.bounds[1]),
                            *enu.lonlat(region.bounds[2], region.bounds[3]))
    water_ll = [w for w in extract.water if w.intersects(region_ll)]
    water_enu = shapely.union_all([enu.to_enu(shapely.make_valid(w)) for w in water_ll]).intersection(region)
    water_parts = [p for p in polygons(water_enu) if p.area >= cfg["min_water_area_m2"]]
    water_parts.sort(key=lambda p: (round(p.bounds[0], 3), round(p.bounds[1], 3)))

    # The lane's highest terrain is the pipeline's (lanes.csr.bin max_terrain_m, nearest DEM
    # pixel every sample_spacing_m along the line), the value the network was built with.
    _, _, lanes, _ = demo_network()
    max_terrain = float(lanes.max_terrain_m[lane_id])
    cruise_height = lane["cruise_alt_m"]
    lane["terrain"] = {
        "comment": "Phase 8 corridor world: heights in metres NAVD88 (USGS 3DEP).",
        "pad_a_elevation_m": round(elev_a, NDIGITS), "pad_b_elevation_m": round(elev_b, NDIGITS),
        "max_terrain_m": round(max_terrain, NDIGITS), "cruise_height_m": cruise_height}
    # Constant cruise altitude above pad A's ground (the EKF origin): highest terrain on the
    # lane plus the airspace cruise height.
    lane["cruise_alt_m"] = round(max_terrain + cruise_height - elev_a, NDIGITS)
    pad_ground = {"A": 0.0, "B": round(elev_b - elev_a, NDIGITS)}
    scene["elevation_m"] = round(elev_a, NDIGITS)
    scene["pad_ground_z_m"] = pad_ground
    scene["slab_side_m"] = yaml.safe_load((PX4 / "config" / "flight.yaml").read_text())["pads"]["slab_side_m"]

    grid, water = terrain_grid(cfg, region, enu, dem, pads_enu, [elev_a, elev_b], water_parts)

    # Buildings near the lane and the pads; none on a pad's apron (its pad is a ground slab).
    bsel = shapely.union_all([axis.buffer(cfg["building_lane_buffer_m"]),
                              *(shapely.Point(p).buffer(cfg["building_pad_buffer_m"]) for p in pads_enu)])
    clear = shapely.union_all([shapely.Point(p).buffer(cfg["pad_clear_radius_m"]) for p in pads_enu])
    w, s = enu.lonlat(bsel.bounds[0], bsel.bounds[1])
    e, n = enu.lonlat(bsel.bounds[2], bsel.bounds[3])
    found = bld.read_cached(RAW / OSM_FILE, manifest["files"]["osm_pennsylvania"]["sha256"], CACHE,
                            (float(w), float(s), float(e), float(n)))
    selected, counts = [], {"height": 0, "levels": 0, "default": 0, "left_out_on_pad": 0}
    for f in found:
        geom = enu.to_enu(f.geom)
        if not geom.intersects(bsel):
            continue
        if geom.intersects(clear):
            counts["left_out_on_pad"] += 1
            continue
        h, src = building_height(f.tags, cfg)
        counts[src] += 1
        selected.append({"osm_id": f.osm_id, "geom": geom, "height_m": h, "source": src})

    terrain = terrain_meshes(grid, cfg["elevation_bands"], elev_a)
    water_m = water_mesh(water, cfg["water_offset_m"], elev_a)
    roads_m, road_ways = road_mesh(extract.roads, region, enu, grid, cfg, elev_a)
    fixed = sum(m.triangles for m in terrain) + water_m.triangles + roads_m.triangles
    for tol in cfg["simplify_tolerances_m"]:
        buildings_m, prisms = building_mesh(selected, grid, tol, cfg, elev_a)
        if fixed + buildings_m.triangles <= cfg["max_triangles"]:
            break
    else:
        raise RuntimeError(f"{fixed + buildings_m.triangles} triangles over the cap {cfg['max_triangles']} "
                           "at the coarsest building simplification")

    meshes = []
    mdir = HERO_DIR / "models" / MODEL / "meshes"
    for k, (band, m) in enumerate(zip(cfg["elevation_bands"], terrain)):
        (mdir / f"terrain_{k}.obj").write_text(m.obj(f"terrain band {k}, below {band['below_m']} m NAVD88"))
        meshes.append((f"terrain_{k}", f"terrain_{k}.obj", band["rgb"], False))
    for name, m, rgb, shadows in (("water", water_m, cfg["water_rgb"], False), ("roads", roads_m, cfg["road_rgb"], False),
                                  ("buildings", buildings_m, cfg["building_rgb"], True)):
        (mdir / f"{name}.obj").write_text(m.obj(name))
        meshes.append((name, f"{name}.obj", rgb, shadows))
    (HERO_DIR / "models" / MODEL / "model.config").write_text(f"""<?xml version="1.0"?>
<model>
  <name>{MODEL}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Generated by pipeline/run.sh hero world. Terrain, water, roads and buildings of the
clip's corridor (visual only). The world includes the meshes directly.</description>
</model>
""")
    (HERO_DIR / "world_src.sdf").write_text(world_sdf(lane, scene, cfg, meshes, pad_ground, elev_a))
    (HERO_DIR / "lane.json").write_text(json.dumps(lane, indent=1) + "\n")
    (HERO_DIR / "scene.json").write_text(json.dumps(scene, indent=1) + "\n")
    np.save(HERO_DIR / "obstacles" / "terrain_z.npy", (grid.z - elev_a).astype(np.float32))
    (HERO_DIR / "obstacles" / "obstacles.json").write_text(json.dumps({
        "comment": "Generated by pipeline/run.sh hero world. World ENU metres, z from pad A's ground.",
        "terrain": {"x0_m": grid.x0, "y0_m": grid.y0, "spacing_m": grid.g, "file": "terrain_z.npy",
                    "diagonal": "cells split along (i, j)-(i+1, j+1)"},
        "buildings": prisms}, indent=None, separators=(",", ":")) + "\n")

    files = sorted(p for p in HERO_DIR.rglob("*") if p.is_file())
    doc = {
        "comment": "Generated by pipeline/run.sh hero world; do not edit. The files listed are git-ignored "
                   "and regenerated by the command; their sha256 here shows two runs are byte-identical.",
        "lane_id": lane_id, "lane": f"{a['name']} -> {b['name']}",
        "sources": {k: {"file": manifest["files"][k]["file"] if "file" in manifest["files"][k] else k,
                        "sha256": manifest["files"][k]["sha256"]}
                    for k in ("osm_pennsylvania", "dem_n41w080", "dem_n41w081")},
        "dem_files": list(DEM_FILES),
        "config_sha256": hashlib.sha256((REPO / "pipeline" / "hero" / "hero.yaml").read_bytes()).hexdigest(),
        "elevation_m": {"pad_a": round(elev_a, NDIGITS), "pad_b": round(elev_b, NDIGITS),
                        "lane_max_terrain": round(max_terrain, NDIGITS)},
        "cruise_alt_above_pad_a_m": lane["cruise_alt_m"],
        "terrain": {"grid_m": grid.g, "cells": int(grid.keep.sum()),
                    "triangles_by_band": [m.triangles for m in terrain]},
        "water": {"polygons": len(water), "surface_m": [round(s, NDIGITS) for _, s in water],
                  "triangles": water_m.triangles},
        "roads": {"ways": road_ways, "triangles": roads_m.triangles},
        "buildings": {**counts, "extruded": len(selected), "prisms": len(prisms),
                      "simplify_tolerance_m": tol, "triangles": buildings_m.triangles},
        "triangles_total": fixed + buildings_m.triangles, "triangles_cap": cfg["max_triangles"],
        "files": {str(p.relative_to(REPO)): {"bytes": p.stat().st_size, "sha256": sha256(p)} for p in files},
    }
    (OUT / "world_manifest.json").write_text(json.dumps(doc, indent=1) + "\n")
    print(json.dumps({k: v for k, v in doc.items() if k not in ("files", "sources")}, indent=1))
    return doc


