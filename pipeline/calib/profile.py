"""Phase 5 step 6: write the fitted parameters as a flight profile the sim config can select
(spec 8.7): configs/flight_profiles/px4_sitl_proxy.toml, from pipeline/calib/fitted_params.json.
Every value stays a placeholder (assumption = true) whose source is the SITL proxy fit."""

import json

from common import CALIB, PROFILE_KEYS, REPO

PROFILE = REPO / "configs" / "flight_profiles" / "px4_sitl_proxy.toml"


def main() -> None:
    fitted = json.loads((CALIB / "fitted_params.json").read_text())
    lines = [
        "# Flight profile fitted to PX4 SITL flights (docs/calibration.md). Generated by",
        "# `pipeline/run.sh calib profile` from pipeline/calib/fitted_params.json; do not edit.",
        "# SITL has no power model: powers come from the energy proxy of spec A57, so every value",
        "# is a placeholder (assumption = true) with source px4-sitl-proxy.",
        "",
        'name = "px4_sitl_proxy"',
        f'source = "{fitted["source"]}"',
        "",
        "[drone]",
    ]
    for key, unit in PROFILE_KEYS.items():
        std = fitted["uncertainty_std"][key]
        lines.append(f'{key} = {{ value = {fitted["params"][key]!r}, unit = "{unit}", assumption = true }}'
                     f"  # bootstrap std {std}")
    PROFILE.parent.mkdir(parents=True, exist_ok=True)
    PROFILE.write_text("\n".join(lines) + "\n")
    print(f"wrote {PROFILE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
